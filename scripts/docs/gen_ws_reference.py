"""Generate docs/architecture/websockets.md from the canonical payloads (#352).

The examples are the fixtures the publisher and consumer tests use
(tests/fixtures/payloads, tests/fixtures/channels), so the reference cannot
drift from the shapes the code is tested against.
tests/unit/infrastructure/test_ws_reference.py fails when the committed file
differs from this output.

    python scripts/docs/gen_ws_reference.py           # rewrite the doc
    python scripts/docs/gen_ws_reference.py --check   # exit 1 on drift
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "architecture" / "websockets.md"

# path, Redis channel, cadence / trigger, frontend reader, [(caption, fixture)]
SOCKETS: list[tuple[str, str, str, str, list[tuple[str, str]]]] = [
    ("/ws/ticks", "ticks", "every tick, throttled to one PUBLISH per 200 ms per symbol (market-data)",
     "top bar mid / bid / ask (`useTicks`, smoothed to 1 s)", [("", "payloads/ticks.json")]),
    ("/ws/vol", "vol_update", "end of each vol scan (about 3 min in market hours)",
     "invalidation beat: the desk re-fetches its surface snapshots (throttled to 30 s)", [("", "payloads/vol_update.json")]),
    ("/ws/risk", "risk_update", "end of each risk cycle (about 2 s)",
     "invalidation beat for the risk and portfolio snapshots (throttled to 15 s)", [("", "payloads/risk_update.json")]),
    ("/ws/orders/{structure_id}", "orders:<structure_id>", "each order status, fill, rejection, cancel or unwind of that structure (execution)",
     "the order ticket while a submit is working", [("", "payloads/orders.json")]),
    ("/ws/positions", "positions", "a position sync that upserted or closed rows, and the monitor's MTM snapshot per position",
     "positions table patches (`positions_changed`), MTM ignored", [("`positions_changed` (execution)", "channels/positions.json"),
                                                                     ("MTM snapshot (position monitor)", "payloads/positions.json")]),
    ("/ws/account", "account", "each account snapshot of the execution engine",
     "cash / margin panels (`account_snapshot.latest` = `GET /portfolio/account` latest)", [("", "channels/account.json")]),
    ("/ws/spot_orders", "spot_orders", "each spot order change",
     "spot blotter rows (`row` = one `GET /trade/spot-orders` row)", [("", "channels/spot_orders.json")]),
    ("/ws/exit_alerts", "exit_alerts", "each exit alert the position monitor raises",
     "not read by the desk today; for tools", [("", "payloads/exit_alerts.json")]),
]

HEADER = """# WebSocket channels

Generated by `scripts/docs/gen_ws_reference.py` from the canonical payloads in
`tests/fixtures/` (#352). Do not edit by hand; change the fixture (and the
publisher test that pins it) and regenerate.

## How the streams work

- **Transport.** `wss://<host>/fx-volatility-trading-system/ws/<name>` in prod
  (nginx strips the prefix), `ws://localhost/ws/<name>` locally. Each socket is a
  one-way stream: the api subscribes to one Redis channel and forwards every
  message to every client, verbatim, as a JSON text frame. Clients send nothing.
- **Access.** Public, like the REST reads. The upgrade is refused with close code
  1008 when the `Origin` header is not on the allowlist (`WS_ALLOWED_ORIGINS` +
  the CORS origins); a client that sends no `Origin` (not a browser) is accepted
  ([security.md](../ops/security.md#websocket-streams)).
- **Delivery.** At most once, no backlog: Redis pub/sub keeps nothing for a
  client that was not connected. After a reconnect, re-read the REST snapshot
  (the desk does this on every reconnect).
- **Types.** The frontend types for these messages live in
  `frontend/src/hooks/streams.ts` and are checked against the same fixtures
  (`frontend/src/hooks/__tests__/wsContract.test.ts`).

| Socket | Redis channel | When a message is sent | Desk reader |
|---|---|---|---|
"""


def render() -> str:
    lines = [HEADER.rstrip("\n")]
    for path, channel, when, reader, _ in SOCKETS:
        lines.append(f"| `{path}` | `{channel}` | {when} | {reader} |")
    lines.append("")
    lines.append("## Message examples")
    for path, _channel, _, _, examples in SOCKETS:
        lines.append("")
        lines.append(f"### `{path}`")
        for caption, fixture in examples:
            data = json.loads((ROOT / "tests" / "fixtures" / fixture).read_text(encoding="utf-8"))
            lines.append("")
            if caption:
                lines.append(f"{caption}, from `tests/fixtures/{fixture}`:")
            else:
                lines.append(f"From `tests/fixtures/{fixture}`:")
            lines.append("")
            lines.append("```json")
            lines.append(json.dumps(data, indent=2, ensure_ascii=False))
            lines.append("```")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run python scripts/docs/gen_ws_reference.py")
            return 1
        print("websockets.md is current")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
